# Boothbridge : compiles the core to native extension modules (Cython, then MinGW gcc)

# python compile_core.py
# Copies the package and main.py to build/stage and replaces every module by a .pyd (Cython translates it to C, gcc builds it), only the __init__ files stay Python.
# PyArmor protects the two __init__ files that carry logic (sources, export). build.py feeds build/stage to PyInstaller, the sources in the repository are never touched.
# 
# python compile_core.py --native    only builds core/fastcore.cpp next to the sources, to run or test the C++ core without a full build
# 
# The C++ core (export.pdb page layout and waveform bands) becomes fastcore.dll beside native.py, the Python versions stay as the reference and the fallback.
# Needs: pip install cython pyarmor, and MinGW gcc (MSYS2 ucrt64: C:\msys64\ucrt64\bin, or on the PATH, or CC and BB_CXX)

from __future__ import annotations

import os
import shutil
import subprocess
import sys
import sysconfig
import time
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parent
STAGE = ROOT / "build" / "stage"
CPP = ROOT / "core" / "fastcore.cpp"
PKG = STAGE / "djapp"

# relative to the package: every module. __init__.py stays Python (a package cannot be a lone
# extension) and __main__.py is the launcher of python -m, the exe starts from main.py
KEEP = ("__init__.py", "__main__.py", "_seal.py", "integrity.py")
CORE = ["*.py", "ui/*.py", "sources/*.py", "export/*.py", "export/cdj/*.py"]

# the __init__ files that carry code (the readers' entry point, the export entry point).
# __init__.py of the package, integrity.py and _seal.py run before the seal is checked: they
# stay plain Python, nothing native may load before the check
PROTECT = ["sources/__init__.py", "export/__init__.py"]
RUNTIME = "pyarmor_runtime_000000"

# Python's semantics, nothing else: Cython would otherwise read `x: int` as a check and type locals as C doubles
DIRECTIVES = {
    "language_level": 3,
    "annotation_typing": False,
    "infer_types": False,
    "binding": True,
    "always_allow_keywords": True,
    "embedsignature": False,
    "emit_code_comments": False,
    "cdivision": False,
    "cpow": False,
}
# no C line number in a traceback, the Python file and line stay
FLAGS = ["-O2", "-fno-strict-aliasing", "-DNDEBUG", "-DMS_WIN64", "-DCYTHON_CLINE_IN_TRACEBACK=0"]
# stack protector and fortified calls, ASLR with high entropy and DEP asked of the loader, no symbol table
HARDENING = ["-fstack-protector-strong", "-D_FORTIFY_SOURCE=2", "-fvisibility=hidden"]
HARDENING_LINK = ["-s", "-Wl,--dynamicbase", "-Wl,--nxcompat", "-Wl,--high-entropy-va", "-Wl,--no-insert-timestamp"]
MINGW = Path(r"C:\msys64\ucrt64\bin")


def core_files() -> list[Path]:
    files = []
    for pat in CORE:
        files += [p for p in sorted(PKG.glob(pat)) if p.name not in KEEP]
    return files


def write_seal():
    # SHA-256 of every native module of the staged package, packed in the executable as _seal.py.
    # Written after the last compilation: a hash taken earlier would be stale
    sys.path.insert(0, str(ROOT))
    from djapp import integrity

    hashes = integrity.scan(PKG)
    lines = [f"    {rel!r}: {digest!r}," for rel, digest in hashes.items()]
    (PKG / "_seal.py").write_text(
        "# generated by compile_core.py, do not edit\n\nHASHES = {\n"
        + "\n".join(lines)
        + "\n}\n",
        encoding="utf-8",
    )
    print(f"seal: {len(hashes)} native modules")


def protect():
    # PyArmor on the files that stay Python. Its runtime goes inside djapp/, so write_seal() hashes it with the other native modules,
    # and only the protected files load it, after the startup check
    try:
        import pyarmor  # noqa: F401
    except ImportError:
        sys.exit("PyArmor is missing: pip install pyarmor")
    work = STAGE / "pyarmor_in"
    out = STAGE / "pyarmor_out"
    for folder in (work, out):
        shutil.rmtree(folder, ignore_errors=True)
    # a small package with only the files to protect, the compiled modules stay out of it
    (work / "djapp").mkdir(parents=True)
    (work / "djapp" / "__init__.py").write_text("", encoding="utf-8")
    for rel in PROTECT:
        (work / "djapp" / rel).parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(PKG / rel, work / "djapp" / rel)
    r = subprocess.run(
        [
            sys.executable,
            "-m",
            "pyarmor.cli",
            "gen",
            "-r",
            "-i",
            "-O",
            str(out),
            "djapp",
        ],
        cwd=work,
        capture_output=True,
        text=True,
        check=False,
    )
    if r.returncode != 0:
        sys.exit("PyArmor failed:\n" + r.stdout[-2000:] + r.stderr[-2000:])
    runtime = out / "djapp" / RUNTIME
    if not (runtime / "pyarmor_runtime.pyd").is_file() and not list(
        runtime.glob("pyarmor_runtime.*")
    ):
        sys.exit("PyArmor produced no runtime package")
    for rel in PROTECT:
        done = out / "djapp" / rel
        if "__pyarmor__" not in done.read_text(encoding="utf-8", errors="ignore"):
            sys.exit(f"PyArmor left {rel} readable")
        shutil.copyfile(done, PKG / rel)
    shutil.rmtree(PKG / RUNTIME, ignore_errors=True)
    shutil.copytree(runtime, PKG / RUNTIME)
    for folder in (work, out):
        shutil.rmtree(folder, ignore_errors=True)
    print(f"PyArmor: {len(PROTECT)} files protected, runtime in djapp/{RUNTIME}")


def stage():
    shutil.rmtree(STAGE, ignore_errors=True)
    shutil.copytree(
        ROOT / "djapp", PKG, ignore=shutil.ignore_patterns("__pycache__", "*.pyc")
    )
    shutil.copyfile(ROOT / "main.py", STAGE / "main.py")


def find_tool(env: str, names: tuple[str, ...]) -> str | None:
    # the variable, the PATH, then the MSYS2 ucrt64 folder
    if os.environ.get(env):
        return os.environ[env]
    for name in names:
        if shutil.which(name):
            return shutil.which(name)
        if (MINGW / (name + ".exe")).is_file():
            return str(MINGW / (name + ".exe"))
    return None


def find_cxx() -> list[str]:
    found = find_tool("BB_CXX", ("g++", "clang++"))
    if not found:
        sys.exit("no C++ compiler: install MSYS2 ucrt64 (g++), or set BB_CXX")
    return [found]


def find_cc() -> str:
    found = find_tool("CC", ("gcc", "clang"))
    if not found:
        sys.exit("no C compiler: install MSYS2 ucrt64 (gcc), or set CC")
    return found


def build_native(dest: Path):
    name = (
        "fastcore.dll"
        if sys.platform == "win32"
        else "libfastcore.dylib"
        if sys.platform == "darwin"
        else "libfastcore.so"
    )
    out = dest / name
    # a previous failed link leaves the import library behind and the linker then refuses to write
    for old in (out, *dest.glob("fastcore.lib"), *dest.glob("fastcore.pdb")):
        # a Python that loaded the DLL holds it for a moment
        for _ in range(20):
            try:
                old.unlink(missing_ok=True)
                break
            except PermissionError:
                time.sleep(0.5)
        else:
            sys.exit(f"{old.name} is in use, close the programs that loaded it")
    # no fused multiply-add: the results must match the Python reference to the last bit
    # -s: no symbols and no .pdb, --gc-sections: only the code that is called stays
    hardening = ["-fstack-protector-strong", "-D_FORTIFY_SOURCE=2"]
    if sys.platform == "win32":
        hardening += ["-static", "-Wl,--dynamicbase", "-Wl,--nxcompat", "-Wl,--high-entropy-va"]
    elif sys.platform != "darwin":
        hardening += ["-Wl,-z,relro", "-Wl,-z,now", "-Wl,-z,noexecstack"]
    cmd = [
        *find_cxx(),
        "-std=c++17",
        "-O2",
        *hardening,
        "-shared",
        "-fPIC",
        "-ffp-contract=off",
        "-fvisibility=hidden",
        "-fno-rtti",
        "-ffunction-sections",
        "-fdata-sections",
        "-s",
        "-Wl,--gc-sections",
        "-o",
        str(out),
        str(CPP),
    ]
    # MinGW finds its own programs and dlls through the PATH
    env = dict(os.environ)
    env["PATH"] = str(Path(cmd[0]).parent) + os.pathsep + env.get("PATH", "")
    r = subprocess.run(cmd, capture_output=True, text=True, check=False, env=env)
    if r.returncode != 0 or not out.is_file():
        sys.exit("C++ build failed:\n" + r.stderr[-3000:])
    for junk in dest.glob("*.lib"):
        junk.unlink()
    for junk in dest.glob("*.pdb"):
        junk.unlink()
    print(
        f"native core: {out.relative_to(ROOT) if out.is_relative_to(ROOT) else out} ({out.stat().st_size // 1024} KB)"
    )
    return out


def compile_one(src: Path, cc: str):
    from Cython.Compiler import Options
    from Cython.Compiler.Main import CompilationOptions
    from Cython.Compiler.Main import compile as cy_compile

    Options.docstrings = False
    rel = src.relative_to(PKG)
    work = STAGE / "cython" / rel.parent
    work.mkdir(parents=True, exist_ok=True)
    c_file = work / (src.stem + ".c")
    res = cy_compile(str(src), CompilationOptions(output_file=str(c_file), compiler_directives=DIRECTIVES, language_level=3))
    if res.num_errors or not c_file.is_file():
        sys.exit(f"Cython failed on {rel}")
    out = src.with_name(src.stem + (sysconfig.get_config_var("EXT_SUFFIX") or ".pyd"))
    libs = Path(sys.base_prefix) / "libs"
    command = [
        cc, "-w", *FLAGS, *HARDENING, "-shared", "-static", f"-I{sysconfig.get_paths()['include']}", str(c_file),
        "-o", str(out), *HARDENING_LINK, f"-L{libs}", f"-l:python{sys.version_info.major}{sys.version_info.minor}.lib",
    ]
    env = dict(os.environ)
    env["PATH"] = str(Path(cc).parent) + os.pathsep + env.get("PATH", "")
    # a scanner may hold a file for a moment: a second try finds it free
    for attempt in range(4):
        r = subprocess.run(command, capture_output=True, text=True, env=env, check=False)
        if r.returncode == 0:
            break
        time.sleep(2)
    if r.returncode != 0:
        sys.exit(f"gcc failed on {rel}:\n{r.stderr[-2500:]}")
    src.unlink()


def main() -> int:
    if "--native" in sys.argv:
        if not CPP.is_file():
            sys.exit("this tree has no C++ core")
        build_native(ROOT / "djapp")
        return 0
    try:
        import Cython  # noqa: F401
    except ImportError:
        sys.exit("Cython is missing: pip install cython")
    cc = find_cc()
    stage()
    if CPP.is_file():
        build_native(PKG)
    files = core_files()
    with ThreadPoolExecutor(max_workers=max(1, (os.cpu_count() or 2) - 1)) as pool:
        for _ in pool.map(lambda f: compile_one(f, cc), files):
            pass
    shutil.rmtree(STAGE / "cython", ignore_errors=True)
    protect()
    write_seal()
    left = [
        p.relative_to(PKG)
        for pat in CORE
        for p in PKG.glob(pat)
        if p.suffix == ".py" and p.name not in KEEP
    ]
    print(f"{len(files)} core modules compiled in {STAGE}, {len(left)} core .py left")
    return 0 if not left else 1


if __name__ == "__main__":
    sys.exit(main())
